"""macOS backend: Seatbelt (`sandbox-exec`), plan §10.3.

UNVERIFIED on a Mac: the profile generator is unit-tested on Linux, but the
base profile (data/seatbelt_base.sb) and the launch have not been tried on
macOS yet. See MACOS.md for the checklist.

There is no mount namespace: the sandbox sees the real filesystem, filtered by
rules on real paths (Seatbelt resolves symlinks, so every path is emitted with
os.path.realpath: /tmp is /private/tmp, /var is /private/var). A "mount" in
the Policy becomes an allow rule; a read-only mount inside a writable area
becomes a deny-write rule. Rules are emitted in the Policy's mount order
(shallower first), since later rules win in SBPL, so deeper paths win as they
do with podman's mounts.
"""

from __future__ import annotations

import os
import re
import shutil
from importlib import resources

from . import BackendError, LaunchSpec
from .podman import run_foreground


def base_profile() -> str:
    return resources.files("xsb").joinpath("data/seatbelt_base.sb").read_text()


def sbpl_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def sbpl_regex(r: str) -> str:
    """A regex literal. #"..." is a raw string (backslashes reach the regex
    engine as written); a double quote can't appear, so it matches any char."""
    return '#"' + r.replace('"', ".") + '"'


def regex_escape(s: str) -> str:
    return "".join(c if c.isalnum() or c in "/-_ " else "\\" + c for c in s)


def glob_regex(pattern: str) -> str:
    """An absolute glob as an SBPL regex matching the path and anything below it.
    `*` and `?` stay within one path component, as with Python's glob."""
    out = []
    i = 0
    while i < len(pattern):
        c = pattern[i]
        if c == "*":
            out.append("[^/]*")
        elif c == "?":
            out.append("[^/]")
        elif c == "[":
            j = pattern.find("]", i + 1)
            if j > i + 1:
                body = pattern[i + 1:j]
                if body.startswith("!"):
                    body = "^" + body[1:]
                out.append("[" + body + "]")
                i = j
            else:
                out.append("\\[")
        else:
            out.append(regex_escape(c))
        i += 1
    return "^" + "".join(out) + "(/.*)?$"


def depth(path: str) -> int:
    return len([p for p in path.split("/") if p])


def ancestors(path: str) -> list[str]:
    out = []
    p = os.path.dirname(path)
    while p not in ("/", ""):
        out.append(p)
        p = os.path.dirname(p)
    return out


def profile(policy, realpath=os.path.realpath) -> str:
    """The Seatbelt profile for a policy. Pure apart from resolving symlinks."""
    lines = ["(version 1)", "(deny default)", "", base_profile().rstrip(), "",
             ";; ---- generated by xsb for this launch ----"]

    # Re-sort by the depth of the real path (stable, so ties keep the Policy's order).
    mounts = sorted(((realpath(m.path), m) for m in policy.mounts), key=lambda x: depth(x[0]))
    # Parent directories must be stat-able for paths to resolve.
    meta = []
    for real, _ in mounts:
        for a in ancestors(real):
            if a not in meta:
                meta.append(a)
    if meta:
        lines.append(";; parent directories of visible paths (metadata only)")
        lines.append("(allow file-read-metadata")
        lines += [f"    (literal {sbpl_str(a)})" for a in sorted(meta)]
        lines[-1] += ")"
        lines.append("")

    # Protected globs as regexes, placed by depth among the mount rules.
    globs = [(depth(r), r) for r in (realpath_prefix(g, realpath) for g in policy.protect_globs)]
    lines.append(";; mounts, protected paths (shallower first; later rules win)")
    for real, m in mounts:
        d = depth(real)
        for gd, g in [x for x in globs if x[0] < d]:
            lines.append(f"(deny file-write* (regex {sbpl_regex(glob_regex(g))}))   ; protected")
        globs = [x for x in globs if x[0] >= d]
        target = f"(subpath {sbpl_str(real)})"
        if m.mode == "rw":
            lines.append(f"(allow file-read* file-write* {target})   ; {m.why}")
        else:
            lines.append(f"(allow file-read* {target})   ; {m.why}")
            lines.append(f"(deny file-write* {target})")
    for _, g in globs:
        lines.append(f"(deny file-write* (regex {sbpl_regex(glob_regex(g))}))   ; protected")
    lines.append("")

    # ~/.xsb stays invisible except for the agent dirs mounted by this launch (I3).
    lines.append(";; ~/.xsb is invisible, except the agent dirs of this launch")
    xh = realpath(policy.xsb_home)
    lines.append(f"(deny file-read* file-write* (subpath {sbpl_str(xh)}))")
    lines += reallow(xh, [realpath(d) for d in policy.agent_dirs.values()])
    # The proxy's runtime dir is invisible (I5), except this launch's TMPDIR.
    lines.append(";; the proxy's runtime dir is invisible, except this launch's TMPDIR")
    rt = realpath(policy.runtime_dir)
    lines.append(f"(deny file-read* file-write* (subpath {sbpl_str(rt)}))")
    lines += reallow(rt, [realpath(policy.tmpdir)] if policy.tmpdir else [])
    lines.append("")

    lines.append(";; network")
    if policy.network == "enforced":
        lines += ["(deny network*)",
                  '(allow network-outbound (remote ip "localhost:*"))',
                  '(allow network-bind (local ip "localhost:*"))',
                  '(allow network-inbound (local ip "localhost:*"))']
    else:
        lines.append("(allow network*)")
    return "\n".join(lines) + "\n"


def reallow(denied: str, dirs: list[str]) -> list[str]:
    """Re-allow dirs inside a denied subtree, with metadata on their parents
    (inside the subtree) so the paths still resolve."""
    out, meta = [], []
    for d in dirs:
        if d.startswith(denied.rstrip("/") + "/"):
            for a in [denied] + [x for x in ancestors(d) if x.startswith(denied + "/")]:
                if a not in meta:
                    meta.append(a)
    for a in sorted(meta):
        out.append(f"(allow file-read-metadata (literal {sbpl_str(a)}))")
    for d in dirs:
        out.append(f"(allow file-read* file-write* (subpath {sbpl_str(d)}))")
    return out


def realpath_prefix(pattern: str, realpath) -> str:
    """Resolve symlinks in the literal leading part of a glob pattern."""
    parts = pattern.split("/")
    for i, part in enumerate(parts):
        if re.search(r"[*?\[]", part):
            head = "/".join(parts[:i]) or "/"
            return realpath(head).rstrip("/") + "/" + "/".join(parts[i:])
    return realpath(pattern)


class SeatbeltBackend:
    name = "seatbelt"

    def check(self) -> list[str]:
        if not shutil.which("sandbox-exec") and not os.path.exists("/usr/bin/sandbox-exec"):
            return ["sandbox-exec not found (it ships with macOS)"]
        return []

    def base_read_paths(self) -> list[str]:
        """System paths the base profile makes readable (for detection checks)."""
        text = base_profile()
        m = re.search(r"\(allow file-read\*\s(.*?)\)\s*\n\s*\n", text, re.S)
        block = m.group(1) if m else ""
        return re.findall(r'\(subpath "([^"]+)"\)', block)

    def command(self, policy) -> LaunchSpec:
        text = profile(policy)
        path = os.path.join(policy.runtime_dir, f"profile-{os.getpid()}.sb")
        argv = ["sandbox-exec", "-f", path, "/usr/bin/env", "-i",
                *[f"{k}={v}" for k, v in policy.env.items()], *policy.command]
        cleanup = [path] + ([policy.tmpdir] if policy.tmpdir else [])
        return LaunchSpec(argv=argv, files={path: text}, cleanup=cleanup,
                          description=f"# Seatbelt profile ({path})\n{text}")

    def launch(self, spec: LaunchSpec) -> int:
        if self.check():
            raise BackendError(self.check()[0])
        for path, text in spec.files.items():
            os.makedirs(os.path.dirname(path), mode=0o700, exist_ok=True)
            with open(path, "w") as f:
                f.write(text)
        try:
            return run_foreground(spec.argv)
        finally:
            for p in spec.cleanup:
                if os.path.isdir(p) and not os.path.islink(p):
                    shutil.rmtree(p, ignore_errors=True)
                else:
                    try:
                        os.unlink(p)
                    except OSError:
                        pass
